let slideshowTimer = null;


function updateSlideshowButton(isPlaying) {

    const slideshowButton =
        document.querySelector('[data-action="slideshow"]');

    const icon =
        slideshowButton.querySelector("i");

    const label =
        slideshowButton.querySelector("span");

    icon.classList.toggle("fa-circle-play", !isPlaying);
    icon.classList.toggle("fa-circle-pause", isPlaying);

    label.textContent =
        isPlaying ? "Stop Slideshow" : "Slideshow";

    slideshowButton.setAttribute(
        "aria-pressed",
        String(isPlaying)
    );
}


function startSlideshow() {

    openLightbox(currentIndex);

    slideshowTimer =
        setInterval(
            nextPhoto,
            3000
        );

    updateSlideshowButton(true);

    showToast(
        "Slideshow started ▶"
    );
}


function stopSlideshow() {

    if (!slideshowTimer) {
        return;
    }

    clearInterval(slideshowTimer);
    slideshowTimer = null;
    updateSlideshowButton(false);
}


document
    .querySelector(
        '[data-action="slideshow"]'
    )
    .addEventListener(
        "click",
        () => {

            if (slideshowTimer) {

                stopSlideshow();

                showToast(
                    "Slideshow stopped"
                );

            } else {

                startSlideshow();

            }

        }
    );


