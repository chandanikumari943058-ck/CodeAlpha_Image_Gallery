let toastTimer;


function showToast(message) {

    const toast =
        document.getElementById("toast");

    toast.querySelector(
        "span"
    ).textContent = message;

    toast.classList.add("show");


    clearTimeout(toastTimer);


    toastTimer =
        setTimeout(
            () => {

                toast.classList.remove(
                    "show"
                );

            },
            2500
        );
}


