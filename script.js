/* =====================================================
   PAGINATION
===================================================== */

function updatePagination(totalPages) {

    document.querySelector(".pagination").style.display =
        showAllPhotos ? "none" : "flex";

    const pageButtons =
        document.querySelectorAll(".page");

    pageButtons.forEach(button => {

        const pageNumber =
            Number(button.textContent.trim());

        const isVisible =
            totalPages <= 1
                ? pageNumber === 1
                : pageNumber <= totalPages;

        button.style.display =
            isVisible ? "inline-flex" : "none";

        button.classList.toggle(
            "active",
            pageNumber === currentPage
        );
    });

    const prevPage =
        document.getElementById("prevPage");

    const nextPage =
        document.getElementById("nextPage");

    prevPage.disabled = currentPage === 1;
    prevPage.style.opacity = currentPage === 1 ? "0.5" : "1";

    nextPage.disabled = currentPage === totalPages;
    nextPage.style.opacity = currentPage === totalPages ? "0.5" : "1";
}


function goToPage(pageNumber) {

    showAllPhotos = false;

    const totalPages =
        Math.max(
            1,
            Math.ceil(
                filteredPhotos.length / photosPerPage
            )
        );

    currentPage =
        Math.min(
            Math.max(1, pageNumber),
            totalPages
        );

    renderGallery(filteredPhotos);
}


/* =====================================================
   RENDER GALLERY
===================================================== */

function renderGallery(list = photos) {

    gallery.innerHTML = "";

    filteredPhotos = list;

    photoNumber.textContent = list.length;

    totalPhotos.textContent = list.length;

    const totalPages =
        Math.max(
            1,
            Math.ceil(list.length / photosPerPage)
        );

    currentPage =
        Math.min(currentPage, totalPages);

    const startIndex =
        (currentPage - 1) * photosPerPage;

    const visiblePhotos =
        showAllPhotos
            ? list
            : list.slice(
                startIndex,
                startIndex + photosPerPage
            );

    updatePagination(totalPages);

    if (list.length === 0) {

        gallery.innerHTML = `
            <div class="no-result">
                <i class="fa-solid fa-image"></i>
                <h3>No Photos Found</h3>
                <p>Try another search or category.</p>
            </div>
        `;

        return;
    }


    visiblePhotos.forEach((photo) => {

        const originalIndex =
            photos.indexOf(photo);

        const card =
            document.createElement("article");

        card.className = "photo-card";

        const liked =
            favorites.includes(originalIndex);


        card.innerHTML = `

            <img
                src="${photo.image}"
                alt="${photo.title}"
                loading="lazy"
                onerror="this.src='https://via.placeholder.com/600x400/10143d/ffffff?text=Image+Not+Found'"
            >

            <div class="photo-overlay"></div>

            <button
                class="like-button ${liked ? "liked" : ""}"
                data-index="${originalIndex}"
            >

                <i class="${liked
                    ? "fa-solid"
                    : "fa-regular"} fa-heart">
                </i>

            </button>

            <div class="photo-title">

                <h3>${photo.title}</h3>

                <span>
                    ${categoryNames[photo.category]}
                </span>

                <p class="photo-description">
                    ${photo.description}
                </p>

            </div>
        `;


        card.addEventListener(
            "click",
            function (event) {

                if (
                    event.target.closest(".like-button")
                ) {
                    return;
                }

                openLightbox(originalIndex);
            }
        );


        const like =
            card.querySelector(".like-button");


        like.addEventListener(
            "click",
            function (event) {

                event.stopPropagation();

                toggleFavorite(originalIndex);
            }
        );


        gallery.appendChild(card);

    });

}


/* =====================================================
   FILTER
===================================================== */

function filterGallery() {

    currentPage = 1;
    showAllPhotos = false;

    const search =
        searchInput.value
            .toLowerCase()
            .trim();


    filteredPhotos =
        photos.filter(photo => {

            const categoryMatch =
                currentCategory === "all" ||
                photo.category === currentCategory;


            const searchMatch =
                photo.title
                    .toLowerCase()
                    .includes(search) ||

                photo.category
                    .toLowerCase()
                    .includes(search) ||

                photo.description
                    .toLowerCase()
                    .includes(search);


            return categoryMatch && searchMatch;

        });


    renderGallery(filteredPhotos);
}


