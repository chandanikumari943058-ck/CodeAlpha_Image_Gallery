document.addEventListener(
    "keydown",
    event => {

        if (
            !lightbox.classList.contains(
                "show"
            )
        ) {
            return;
        }


        if (event.key === "Escape") {
            closeLightbox();
        }


        if (event.key === "ArrowRight") {
            nextPhoto();
        }


        if (event.key === "ArrowLeft") {
            previousPhoto();
        }


        if (event.key === "+") {
            document
                .getElementById("zoomIn")
                .click();
        }


        if (event.key === "-") {
            document
                .getElementById("zoomOut")
                .click();
        }

    }
);


