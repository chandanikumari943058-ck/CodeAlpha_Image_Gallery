/* =====================================================
   LIGHTBOX
===================================================== */

function openLightbox(index) {

    currentIndex = index;

    zoomLevel = 1;

    updateLightbox();

    lightbox.classList.add("show");

    document.body.style.overflow = "hidden";
}


function updateLightbox() {

    const photo =
        photos[currentIndex];


    lightImage.src =
        photo.image;

    lightboxBackdrop.style.backgroundImage =
        `linear-gradient(rgba(1, 2, 15, .68), rgba(1, 2, 15, .82)), url("${photo.image}")`;


    lightImage.alt =
        photo.title;


    lightTitle.textContent =
        photo.title;


    lightCategory.textContent =
        categoryNames[photo.category];


    lightDescription.textContent =
        photo.description;


    lightCounter.textContent =
        `${currentIndex + 1} / ${photos.length}`;


    lightImage.style.transform =
        `scale(${zoomLevel})`;


    const liked =
        favorites.includes(currentIndex);


    const likeButton =
        document.getElementById("likeLight");


    likeButton.innerHTML =
        liked
            ? `<i class="fa-solid fa-heart"></i> Liked`
            : `<i class="fa-regular fa-heart"></i> Like`;


    updateFeatured(photo);
}


